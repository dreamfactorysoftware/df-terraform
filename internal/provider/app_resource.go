func (r *AppResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	client, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *client.Client, got: %T.", req.ProviderData),
		)
		return
	}

	r.client = client
}

func (r *AppResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data AppResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)

	if resp.Diagnostics.HasError() {
		return
	}

	app := client.App{
		Name:        data.Name.ValueString(),
		Description: data.Description.ValueString(),
		IsActive:    data.IsActive.ValueBool(),
		Type:        int(data.Type.ValueInt64()),
	}

	if !data.RoleID.IsNull() && !data.RoleID.IsUnknown() {
		roleID := int(data.RoleID.ValueInt64())
		app.RoleID = &roleID
	}

	tflog.Debug(ctx, "Creating DreamFactory app", map[string]interface{}{
		"name": app.Name,
	})

	id, apiKey, err := r.client.CreateApp(app)
	if err != nil {
		resp.Diagnostics.AddError(
			"Failed to Create App",
			fmt.Sprintf("Unable to create app %q: %s\n\n"+
				"Please verify that:\n"+
				"- The app name is unique\n"+
				"- The role_id (if specified) exists",
				data.Name.ValueString(), err),
		)
		return
	}

	data.ID = types.StringValue(strconv.Itoa(id))
	data.APIKey = types.StringValue(apiKey)

	tflog.Info(ctx, "Created DreamFactory app", map[string]interface{}{
		"id":   id,
		"name": data.Name.ValueString(),
	})

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *AppResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data AppResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)

	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(data.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(
			"Invalid App ID",
			fmt.Sprintf("Unable to parse app ID %q: %s", data.ID.ValueString(), err),
		)
		return
	}

	tflog.Debug(ctx, "Reading DreamFactory app", map[string]interface{}{
		"id": id,
	})

	app, err := r.client.GetApp(id)
	if err != nil {
		if errors.Is(err, client.ErrNotFound) {
			tflog.Info(ctx, "App not found, removing from state", map[string]interface{}{
				"id": id,
			})
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError(
			"Failed to Read App",
			fmt.Sprintf("Unable to read app with ID %d: %s", id, err),
		)
		return
	}

	data.Name = types.StringValue(app.Name)
	data.APIKey = types.StringValue(app.APIKey)
	data.Description = types.StringValue(app.Description)
	data.IsActive = types.BoolValue(app.IsActive)
	data.Type = types.Int64Value(int64(app.Type))
	if app.RoleID != nil {
		data.RoleID = types.Int64Value(int64(*app.RoleID))
	} else {
		data.RoleID = types.Int64Null()
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *AppResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var data AppResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)

	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(data.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(
			"Invalid App ID",
			fmt.Sprintf("Unable to parse app ID %q: %s", data.ID.ValueString(), err),
		)
		return
	}

	app := client.App{
		Name:        data.Name.ValueString(),
		Description: data.Description.ValueString(),
		IsActive:    data.IsActive.ValueBool(),
		Type:        int(data.Type.ValueInt64()),
	}

	if !data.RoleID.IsNull() && !data.RoleID.IsUnknown() {
		roleID := int(data.RoleID.ValueInt64())
		app.RoleID = &roleID
	}

	tflog.Debug(ctx, "Updating DreamFactory app", map[string]interface{}{
		"id":   id,
		"name": app.Name,
	})

	err = r.client.UpdateApp(id, app)
	if err != nil {
		resp.Diagnostics.AddError(
			"Failed to Update App",
			fmt.Sprintf("Unable to update app %q (ID: %d): %s", data.Name.ValueString(), id, err),
		)
		return
	}

	tflog.Info(ctx, "Updated DreamFactory app", map[string]interface{}{
		"id":   id,
		"name": data.Name.ValueString(),
	})

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *AppResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data AppResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)

	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(data.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(
			"Invalid App ID",
			fmt.Sprintf("Unable to parse app ID %q: %s", data.ID.ValueString(), err),
		)
		return
	}

	tflog.Debug(ctx, "Deleting DreamFactory app", map[string]interface{}{
		"id":   id,
		"name": data.Name.ValueString(),
	})

	err = r.client.DeleteApp(id)
	if err != nil {
		if errors.Is(err, client.ErrNotFound) {
			// Already deleted, this is fine
			tflog.Info(ctx, "App already deleted", map[string]interface{}{
				"id": id,
			})
			return
		}
		resp.Diagnostics.AddError(
			"Failed to Delete App",
			fmt.Sprintf("Unable to delete app %q (ID: %d): %s", data.Name.ValueString(), id, err),
		)
		return
	}

	tflog.Info(ctx, "Deleted DreamFactory app", map[string]interface{}{
		"id":   id,
		"name": data.Name.ValueString(),
	})
}

func (r *AppResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
